#!/usr/bin/env python3
"""Audit Storytold Craft repos via the GitHub API (no clones, near-zero disk).

Requires an authenticated `gh` CLI. Writes docs/storytold-audit.md.
Usage: python3 scripts/audit_storytold.py
"""
import base64
import json
import re
import subprocess
import sys
from pathlib import Path

ORG = "storytold"
REPOS = [
    "photocraft", "lightcraft", "filmcraft", "designcraft", "vectorcraft",
    "pdfcraft", "effectcraft", "wordcraft", "deckcraft", "gridcraft",
    "cadcraft", "soundcraft", "figcraft",
    "craft-launcher", "craft-libs", "craft-fonts", "artcraft",
]
OUT = Path(__file__).resolve().parent.parent / "docs" / "storytold-audit.md"


def gh(path: str):
    """Return parsed JSON from a gh api call, or None on failure."""
    res = subprocess.run(["gh", "api", path], capture_output=True, text=True)
    if res.returncode != 0:
        return None
    try:
        return json.loads(res.stdout)
    except json.JSONDecodeError:
        return None


def readme_text(repo: str) -> str:
    data = gh(f"repos/{ORG}/{repo}/readme")
    if not data or "content" not in data:
        return ""
    return base64.b64decode(data["content"]).decode("utf-8", errors="replace")


def license_label(meta: dict, root_names: set) -> str:
    lic = (meta.get("license") or {}).get("spdx_id")
    if lic and lic != "NOASSERTION":
        return lic
    files = sorted(n for n in root_names if n.upper().startswith(("LICENSE", "COPYING")))
    return "files: " + ", ".join(files) if files else "NONE FOUND"


def surface(readme: str, root_names: set) -> str:
    found = []
    low = readme.lower()
    if re.search(r"\bmcp\b", low):
        found.append("MCP")
    if re.search(r"\bcli\b|command[- ]line", low):
        found.append("CLI")
    if "script" in low and "python" in low:
        found.append("scripting")
    if "llms.txt" in {n.lower() for n in root_names}:
        found.append("llms.txt")
    return ", ".join(found) if found else "none mentioned"


def maturity(readme: str) -> str:
    low = readme.lower()
    for word in ("early alpha", "alpha", "beta", "experimental", "pre-release"):
        if word in low:
            return word
    return "not stated"


def audit(repo: str) -> dict:
    meta = gh(f"repos/{ORG}/{repo}")
    if not meta:
        return {"repo": repo, "error": "API call failed or repo not found"}
    contents = gh(f"repos/{ORG}/{repo}/contents") or []
    root_names = {c["name"] for c in contents if isinstance(c, dict)}
    rel = gh(f"repos/{ORG}/{repo}/releases/latest")
    readme = readme_text(repo)
    return {
        "repo": repo,
        "license": license_label(meta, root_names),
        "stars": meta.get("stargazers_count"),
        "pushed": (meta.get("pushed_at") or "")[:10],
        "release": rel.get("tag_name") if isinstance(rel, dict) else "none",
        "size_mb": round((meta.get("size") or 0) / 1024, 1),
        "archived": meta.get("archived"),
        "surface": surface(readme, root_names),
        "maturity": maturity(readme),
        "cargo": "yes" if "Cargo.toml" in root_names else "no",
    }


def render(rows: list) -> str:
    lines = [
        "# Storytold Craft audit",
        "",
        "Generated by `scripts/audit_storytold.py` from the GitHub API. "
        "README keyword matches are hints, not proof; confirm in the repo.",
        "",
        "| Repo | License | Stars | Last push | Latest release | Size MB | Maturity | Agent surface | Cargo |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        if "error" in r:
            lines.append(f"| {r['repo']} | {r['error']} | | | | | | | |")
            continue
        lines.append(
            f"| {r['repo']} | {r['license']} | {r['stars']} | {r['pushed']} | "
            f"{r['release'] or 'none'} | {r['size_mb']} | {r['maturity']} | "
            f"{r['surface']} | {r['cargo']} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    rows = []
    for repo in REPOS:
        print(f"auditing {repo}...", file=sys.stderr)
        rows.append(audit(repo))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(rows))
    print(f"wrote {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
